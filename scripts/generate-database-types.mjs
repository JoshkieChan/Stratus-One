// Generate types from the repository's real migrations, without a hosted project.
import { PGlite } from '@electric-sql/pglite';
import { readdir, readFile, writeFile } from 'node:fs/promises';
const db = new PGlite();
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;`);
  for (const file of (await readdir('supabase/migrations')).filter(file => file.endsWith('.sql')).sort()) {
    await db.exec(await readFile(`supabase/migrations/${file}`, 'utf8'));
  }
  const { rows } = await db.query(`select table_name,column_name,data_type,is_nullable,column_default from information_schema.columns where table_schema='public' order by table_name,ordinal_position`);
  const { rows: foreignKeys } = await db.query(`select c.conname as name, t.relname as source, r.relname as target,
    array(select a.attname from unnest(c.conkey) with ordinality k(id,pos) join pg_attribute a on a.attrelid=c.conrelid and a.attnum=k.id order by k.pos) as columns,
    array(select a.attname from unnest(c.confkey) with ordinality k(id,pos) join pg_attribute a on a.attrelid=c.confrelid and a.attnum=k.id order by k.pos) as referenced
    from pg_constraint c join pg_class t on t.oid=c.conrelid join pg_class r on r.oid=c.confrelid
    join pg_namespace n on n.oid=t.relnamespace where c.contype='f' and n.nspname='public'`);
  let output = '// Generated by npm run db:types from versioned migrations. Do not edit manually.\n';
  output += 'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n';
  output += 'export type Database = { public: { Tables: {\n';
  for (const table of [...new Set(rows.map(row => row.table_name))]) {
    const columns = rows.filter(row => row.table_name === table);
    output += `  ${table}: {\n`;
    for (const mode of ['Row','Insert','Update']) {
      output += `    ${mode}: {\n`;
      for (const column of columns) {
        const type = ['integer','bigint','numeric','double precision','real'].includes(column.data_type) ? 'number' : column.data_type === 'jsonb' ? 'Json' : column.data_type === 'boolean' ? 'boolean' : 'string';
        const optional = mode === 'Update' || (mode === 'Insert' && (column.column_default !== null || column.is_nullable === 'YES'));
        output += `      ${column.column_name}${optional ? '?' : ''}: ${type}${column.is_nullable === 'YES' ? ' | null' : ''};\n`;
      }
      output += '    };\n';
    }
    output += '    Relationships: [\n';
    for (const fk of foreignKeys.filter(key => key.source === table)) {
      output += `      { foreignKeyName: ${JSON.stringify(fk.name)}; columns: ${JSON.stringify(fk.columns)}; isOneToOne: false; referencedRelation: ${JSON.stringify(fk.target)}; referencedColumns: ${JSON.stringify(fk.referenced)} },\n`;
    }
    output += '    ];\n  };\n';
  }
  output += '}; Views: { [_ in never]: never }; Functions: { [_ in never]: never }; Enums: { [_ in never]: never }; CompositeTypes: { [_ in never]: never } } };\n';
  const path = 'src/types/database.ts';
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')).replaceAll('\r\n', '\n') !== output) throw new Error('Database types are stale. Run npm run db:types.');
  } else await writeFile(path, output);
} finally { await db.close(); }
